// Regenerate the "JS API reference" section of docs/src/SUMMARY.md from the TypeDoc
// output (run after `typedoc`). mdBook only renders pages listed in SUMMARY.md, so each
// generated page must be linked here. Edits only the text between the js-api markers.
import { readdirSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "docs/src";
const API = "ringo-flow/js-api";
const SUMMARY = join(SRC, "SUMMARY.md");
const START = "<!-- js-api:start (generated by `npm run docs:js`) -->";
const END = "<!-- js-api:end -->";

const page = (sub) => {
  const dir = join(SRC, API, sub);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => `  - [${f.replace(/\.md$/, "")}](${API}/${sub}/${f})`);
};

const lines = [
  `- [JS API reference](${API}/README.md)`,
  ...page("classes"),
  ...page("functions"),
  ...page("interfaces"),
  ...page("enumerations"),
  ...page("type-aliases"),
];

let summary = readFileSync(SUMMARY, "utf8");
const a = summary.indexOf(START);
const b = summary.indexOf(END);
if (a === -1 || b === -1) throw new Error(`js-api markers not found in ${SUMMARY}`);
summary = summary.slice(0, a) + START + "\n" + lines.join("\n") + "\n" + summary.slice(b);
writeFileSync(SUMMARY, summary);
console.log(`Updated ${SUMMARY}: ${lines.length} JS API entries.`);
