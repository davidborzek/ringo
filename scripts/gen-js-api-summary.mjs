// Regenerate the "JS API reference" section of docs/src/SUMMARY.md from the TypeDoc
// output (run after `typedoc`). mdBook only renders pages listed in SUMMARY.md, so each
// generated page must be linked here. Edits only the text between the js-api markers.
import { readdirSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const SRC = "docs/src";
const API = "ringo-flow/js-api";
const SUMMARY = join(SRC, "SUMMARY.md");
const START = "<!-- js-api:start (generated by `npm run docs:js`) -->";
// TypeDoc's per-directory overview page (`entryFileName` in typedoc.json). It must be
// `index.md`, not the plugin's default `README.md`: mdBook renders a `README.md`
// chapter as `index.html` but rewrites links to it as `README.html` — a dead link.
const ENTRY = "index.md";
const END = "<!-- js-api:end -->";

const page = (sub) => {
  const dir = join(SRC, API, sub);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => `  - [${f.replace(/\.md$/, "")}](${API}/${sub}/${f})`);
};

// A `declare namespace` (e.g. `scenario.each`) is rendered into a nested module tree
// instead of the flat kind directories above, so walk whatever else TypeDoc emitted.
// Without this the API overview links to a page mdBook never renders.
const KIND_DIRS = new Set([
  "classes",
  "functions",
  "interfaces",
  "enumerations",
  "type-aliases",
]);

const namespacePages = () => {
  const walk = (dir) =>
    readdirSync(dir, { withFileTypes: true })
      .sort((x, y) => x.name.localeCompare(y.name))
      .flatMap((e) =>
        e.isDirectory()
          ? walk(join(dir, e.name))
          : e.name.endsWith(".md")
            ? [join(dir, e.name)]
            : [],
      );

  const pages = readdirSync(join(SRC, API), { withFileTypes: true })
    .filter((e) => e.isDirectory() && !KIND_DIRS.has(e.name))
    .sort((x, y) => x.name.localeCompare(y.name))
    .flatMap((e) => walk(join(SRC, API, e.name)))
    .map((path) => {
      const parts = path.split("/");
      const file = parts.at(-1);
      const href = relative(SRC, path);
      // A namespace's own overview page (…/namespaces/<ns>/index.md) is the parent
      // entry; its members (…/namespaces/<ns>/<kind>/<member>.md) nest under it as
      // `<ns>.<member>`. The overview must be listed too — the API index links to
      // it, and mdBook only renders what SUMMARY.md names.
      const isOverview = file === ENTRY;
      const ns = isOverview ? parts.at(-2) : parts.at(-3);
      return isOverview
        ? { ns, sort: 0, line: `  - [${ns} (namespace)](${href})` }
        : { ns, sort: 1, line: `    - [${ns}.${file.replace(/\.md$/, "")}](${href})` };
    });

  // Group by namespace, overview first — mdBook needs the parent before its children.
  return pages
    .sort((x, y) => x.ns.localeCompare(y.ns) || x.sort - y.sort)
    .map((p) => p.line);
};

const lines = [
  `- [JS API reference](${API}/${ENTRY})`,
  ...page("classes"),
  ...page("functions"),
  ...namespacePages(),
  ...page("interfaces"),
  ...page("enumerations"),
  ...page("type-aliases"),
];

let summary = readFileSync(SUMMARY, "utf8");
const a = summary.indexOf(START);
const b = summary.indexOf(END);
if (a === -1 || b === -1) throw new Error(`js-api markers not found in ${SUMMARY}`);
summary = summary.slice(0, a) + START + "\n" + lines.join("\n") + "\n" + summary.slice(b);
writeFileSync(SUMMARY, summary);
console.log(`Updated ${SUMMARY}: ${lines.length} JS API entries.`);
